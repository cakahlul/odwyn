import {newPageWithoutTutorials} from '../tests/browser-page.js';
import {test,expect} from 'bun:test';
import {chromium} from 'playwright';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {EventEmitter} from 'node:events';
import {createApp} from '../server.js';
import {defaults} from '../public/profile.js';

test('create and switch homes, preserve drafts, link settings, and scope downloads',async()=>{
  const directory=mkdtempSync(join(tmpdir(),'odwyn-homes-ui-'));
  const codex=new EventEmitter();codex.request=async()=>({account:null});codex.stop=()=>{};
  const options={directory,user:'owner',password:'test-password-long-enough',providerOptions:{codex}};
  let app;const server=Bun.serve({hostname:'127.0.0.1',port:0,fetch:(req,srv)=>app.fetch(req,srv)});
  app=createApp({...options,origin:server.url.origin});
  app.runtime.state.globalProvider.configured=true;
  app.runtime.state.customization={...defaults,name:'Home agent'};app.runtime.state.agents[0].customization=app.runtime.state.customization;app.runtime.changed();
  const browser=await chromium.launch(),context=await browser.newContext({httpCredentials:{username:options.user,password:options.password}}),page=await newPageWithoutTutorials(context),errors=[];
  page.on('pageerror',error=>errors.push(error.message));page.on('dialog',dialog=>dialog.accept());page.setDefaultTimeout(7000);
  try {
    await page.goto(server.url.href);await page.locator('#workspace-home:not([disabled])').waitFor();
    expect(await page.locator('#workspace-current-name').textContent()).toBe('Default');
    await page.locator('#new-chat').click();
    await page.locator('#prompt').fill('Home draft');
    await page.locator('#workspace-home').click();await page.locator('#new-workspace').click();await page.locator('#workspace-home-name').fill('Research');
    await page.locator('#workspace-create-form button').click();
    await page.waitForURL('**/?workspace=*');await page.locator('#workspace-home:not([disabled])').waitFor();
    const id=new URL(page.url()).searchParams.get('workspace');
    expect(id).not.toBe('default');expect(await page.locator('#prompt').inputValue()).toBe('');
    // Configure the new home without connecting any external provider.
    await page.evaluate(async profile=>{
      await fetch('/api/customization'+location.search,{method:'PUT',headers:{'content-type':'application/json'},body:JSON.stringify(profile)});
      await fetch('/api/provider'+location.search+'&scope=global',{method:'PUT',headers:{'content-type':'application/json'},body:JSON.stringify({type:'codex',model:'gpt-6.1-sol'})});
    },{...defaults,name:'Research agent'});
    await page.reload();await page.locator('#workspace-home:not([disabled])').waitFor();
    await page.locator('#tools-open').click();await page.locator('[data-view="workflows"]').click();
    await page.locator('[data-workflow-new]').click();
    const reviewer=await page.evaluate(async profile=>(await(await fetch('/api/agents'+location.search,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(profile)})).json()),{...defaults,name:'Reviewer'});
    await page.locator(`#reply-agent option[value="${reviewer.id}"]`).waitFor({state:'attached'});
    await page.locator('#workflow-name').fill('feature delivery');
    await page.locator('.workflow-first-step').click();await page.locator('[data-wf-add-type="room"]').click();
    await page.locator('[data-wf-field="step.prompt"]').fill('Deliver the reviewed feature.');
    await page.locator('[data-wf-room-configure]').click();
    expect(await page.locator('#room-dialog .modal-description').textContent()).toContain('click Save at the top of the workflow editor');
    await page.locator('#room-name').fill('Feature review');
    await page.locator(`#room-agent-options input[value="${reviewer.id}"]`).check();
    await page.getByRole('button',{name:'Apply stage',exact:true}).click();
    await page.locator('#room-dialog').waitFor({state:'hidden'});
    expect(await page.locator('#workflow-editor').evaluate(node=>node.open)).toBe(true);
    expect(await page.evaluate(async()=>(await(await fetch('/api/workflows'+location.search)).json()).length)).toBe(0);
    await page.locator('#workflow-form button[type="submit"]').click();
    await page.locator('#workflow-editor').waitFor({state:'hidden'});
    await page.locator('.workflow-row h3').filter({hasText:'feature delivery'}).waitFor();
    expect(await page.evaluate(async()=>(await(await fetch('/api/workflows'+location.search)).json()).map(w=>w.name))).toEqual(['feature delivery']);
    expect(await page.evaluate(async()=>(await(await fetch('/api/workflows')).json()).length)).toBe(0);
    await page.reload();await page.locator('.workflow-row h3').filter({hasText:'feature delivery'}).waitFor();
    await page.locator('#new-chat').click();
    await page.locator('#prompt').fill('Research draft');
    const uploaded=await page.evaluate(async()=>{
      const form=new FormData();form.append('file',new File(['Research file'],'research.txt'));
      return (await fetch('/api/files'+location.search,{method:'POST',body:form})).json();
    });
    expect(await page.evaluate(async fileId=>(await fetch('/api/files/'+fileId)).status,uploaded.id)).toBe(404);
    expect(await page.evaluate(async fileId=>(await fetch('/api/files/'+fileId+location.search)).text(),uploaded.id)).toBe('Research file');
    await page.locator('#settings-open').click();await page.locator('[data-settings-section=sharing]').click();
    await page.locator('[data-share-setting=appearance]').check();
    await page.locator('#toast').filter({hasText:'Shared.'}).waitFor();
    await page.locator('[data-share-setting=provider]').check();
    await page.locator('#security-password').fill(options.password);
    const shared=page.waitForResponse(response=>response.url().includes('/api/workspaces/share') && response.request().postData()?.includes('"kind":"provider"'));
    await page.getByRole('button',{name:'Confirm exact request',exact:true}).click();expect((await shared).status()).toBe(200);
    await page.getByRole('button',{name:'Close settings',exact:true}).click();
    await page.locator('#workspace-home').click();await page.locator('[data-workspace-id=default]').click();await page.waitForURL(url=>!url.search);
    await page.waitForFunction(()=>document.querySelector('#prompt').value==='Home draft');
    await page.locator('#workspace-home').click();await page.locator(`[data-workspace-id="${id}"]`).click();await page.waitForURL('**/?workspace=*');
    await page.waitForFunction(()=>document.querySelector('#prompt').value==='Research draft');
    await page.evaluate(async()=>fetch('/api/appearance'+location.search,{method:'PUT',headers:{'content-type':'application/json'},body:JSON.stringify({palette:'paper',motion:'reduced',navigation:'sidebar'})}));
    await page.waitForFunction(()=>document.documentElement.dataset.navigation==='sidebar');
    for(const width of [320,768,1440]) {
      await page.setViewportSize({width,height:900});
      if(width===320)await page.waitForFunction(()=>document.documentElement.classList.contains('sidebar-collapsed'));
      expect(await page.locator('.topbar').evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true);
      if(!await page.locator('#workspace-home').isVisible()) await page.locator('#conversation-menu-open').click();
      expect(await page.locator('#workspace-home').isVisible()).toBe(true);
      await page.locator('#workspace-home').focus();await page.keyboard.press('Enter');await page.locator('#workspace-menu').waitFor({state:'visible'});
      expect(await page.locator('#workspace-home').getAttribute('aria-expanded')).toBe('true');
      const bounds=await page.locator('#workspace-menu').boundingBox();expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(width);
      await page.keyboard.press('Escape');expect(await page.locator('#workspace-menu').isVisible()).toBe(false);
      await page.locator('#conversation-menu-open').click();
      expect(await page.locator('#new-room-top').isVisible()).toBe(true);
      await page.keyboard.press('Escape');
      if(width===320)await page.screenshot({path:'/tmp/odwyn-workspace-mobile.png'});
    }
    await page.locator('#settings-open').click();await page.locator('[data-settings-section=workspaces]').click();
    await page.locator('#workspace-manage-home').selectOption('default');expect(await page.locator('#workspace-delete').isDisabled()).toBe(true);
    await page.locator('#workspace-manage-home').selectOption(id);await page.locator('#workspace-rename-name').fill('Research lab');await page.locator('#workspace-rename-name').press('Enter');
    await page.locator('#toast').filter({hasText:'Workspace renamed.'}).waitFor();
    expect(await page.locator('#workspace-current-name').textContent()).toBe('Research lab');
    page.removeAllListeners('dialog');page.once('dialog',async dialog=>{expect(dialog.message()).toContain('Research lab');expect(dialog.message()).toContain('cannot be undone');await dialog.dismiss();});
    await page.locator('#workspace-delete').click();expect(await page.evaluate(()=>new URL(location.href).searchParams.get('workspace'))).toBe(id);
    page.once('dialog',dialog=>dialog.accept());await page.locator('#workspace-delete').click();await page.waitForURL(url=>!url.search);
    await page.locator('#workspace-home:not([disabled])').waitFor();expect(await page.locator('[data-workspace-id]').count()).toBe(1);
    expect(await page.evaluate(id=>sessionStorage.getItem(`odwyn-drafts:${id}`),id)).toBeNull();
    expect(errors).toEqual([]);
  } finally {await browser.close();server.stop(true);await app.close();rmSync(directory,{recursive:true,force:true});}
},30000);
